/*
# SMM OPTIMA core schema

Creates everything the SMM panel needs: user profiles with balances, service catalog,
provider connections, orders, payments, support tickets, announcements and site settings.

1. New Tables
- `profiles` – one row per account (username, email, role user/admin, balance, total_spent,
  affiliate earnings, api_key, referred_by, status active/banned).
- `settings` – single row (id = 1) of public site settings (name, bKash number, exchange rate,
  contacts, affiliate rate, minimum deposit).
- `categories` – service categories grouped by platform.
- `services` – sellable services with price per 1000, min/max, refill/cancel flags.
- `providers` – upstream SMM providers (API url + key). Admin only.
- `service_sources` – link between a service and its provider service ID + provider cost. Admin only,
  so cost prices are never visible to customers.
- `orders` – customer orders with status, start count, remains, refund tracking.
- `payments` – deposits (bKash manual, admin adjustments, affiliate transfers).
- `tickets`, `ticket_messages` – support conversations.
- `announcements` – the Updates feed.

2. Security
- RLS enabled on every table.
- Customers can only read their own profile, orders, payments and tickets.
- Balance, role, status and spending columns are NOT writable by customers; they only change through
  SECURITY DEFINER functions that check the caller.
- Orders and payments are created only through functions that compute prices on the server.
- Admin access is decided by `profiles.role = 'admin'`, which customers cannot change.

3. Functions
- `is_admin()`, `tier_discount()`, `place_order()`, `submit_bkash_payment()`, `request_refill()`,
  `request_cancel()`, `regenerate_api_key()`, `transfer_affiliate_earnings()`, `settle_order()`
  (service role only), and admin functions `admin_set_order_status()`, `admin_review_payment()`,
  `admin_adjust_balance()`, `admin_update_user()`.
*/

CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username text NOT NULL,
  email text NOT NULL,
  full_name text NOT NULL DEFAULT '',
  whatsapp text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','banned')),
  balance numeric(14,4) NOT NULL DEFAULT 0,
  total_spent numeric(14,4) NOT NULL DEFAULT 0,
  affiliate_earnings numeric(14,4) NOT NULL DEFAULT 0,
  api_key text NOT NULL DEFAULT encode(extensions.gen_random_bytes(16), 'hex'),
  referred_by uuid REFERENCES profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_lower_key ON profiles (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS profiles_api_key_key ON profiles (api_key);
CREATE INDEX IF NOT EXISTS profiles_referred_by_idx ON profiles (referred_by);

CREATE TABLE IF NOT EXISTS settings (
  id int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  site_name text NOT NULL DEFAULT 'SMM OPTIMA',
  bkash_number text NOT NULL DEFAULT '',
  bkash_account_type text NOT NULL DEFAULT 'Personal',
  usd_to_bdt numeric(10,2) NOT NULL DEFAULT 125,
  min_deposit_usd numeric(10,2) NOT NULL DEFAULT 1,
  affiliate_rate numeric(5,2) NOT NULL DEFAULT 5,
  whatsapp text NOT NULL DEFAULT '',
  telegram text NOT NULL DEFAULT '',
  support_email text NOT NULL DEFAULT '',
  notice text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS categories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  platform text NOT NULL DEFAULT 'Other',
  sort_order int NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id uuid NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  type text NOT NULL DEFAULT 'Default',
  rate numeric(14,4) NOT NULL CHECK (rate >= 0),
  min_qty int NOT NULL DEFAULT 10 CHECK (min_qty >= 1),
  max_qty int NOT NULL DEFAULT 10000,
  refill boolean NOT NULL DEFAULT false,
  cancel boolean NOT NULL DEFAULT false,
  avg_time text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS services_category_idx ON services (category_id);

CREATE TABLE IF NOT EXISTS providers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  api_url text NOT NULL,
  api_key text NOT NULL,
  balance numeric(14,4),
  currency text NOT NULL DEFAULT 'USD',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS service_sources (
  service_id bigint PRIMARY KEY REFERENCES services(id) ON DELETE CASCADE,
  provider_id uuid NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  provider_service_id text NOT NULL,
  provider_rate numeric(14,4) NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS service_sources_provider_idx ON service_sources (provider_id);

CREATE TABLE IF NOT EXISTS orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  service_id bigint REFERENCES services(id) ON DELETE SET NULL,
  service_name text NOT NULL,
  link text NOT NULL,
  quantity int NOT NULL,
  charge numeric(14,4) NOT NULL,
  cost numeric(14,4) NOT NULL DEFAULT 0,
  provider_id uuid REFERENCES providers(id) ON DELETE SET NULL,
  provider_service_id text,
  provider_order_id text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','processing','in_progress','completed','partial','canceled')),
  start_count int,
  remains int,
  refunded numeric(14,4) NOT NULL DEFAULT 0,
  refill_status text NOT NULL DEFAULT 'none' CHECK (refill_status IN ('none','requested','sent','failed')),
  cancel_requested boolean NOT NULL DEFAULT false,
  provider_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);

CREATE TABLE IF NOT EXISTS payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  method text NOT NULL CHECK (method IN ('bkash','stripe','admin','affiliate')),
  amount_usd numeric(14,4) NOT NULL,
  amount_bdt numeric(14,2),
  trx_id text,
  sender_number text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS payments_user_idx ON payments (user_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS payments_bkash_trx_key ON payments (upper(trx_id)) WHERE method = 'bkash' AND status <> 'rejected';

CREATE TABLE IF NOT EXISTS tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  subject text NOT NULL CHECK (char_length(subject) BETWEEN 2 AND 120),
  order_ref text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','answered','closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tickets_user_idx ON tickets (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS ticket_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id bigint NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  from_admin boolean NOT NULL DEFAULT false,
  message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 5000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ticket_messages_ticket_idx ON ticket_messages (ticket_id, created_at);

CREATE TABLE IF NOT EXISTS announcements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  body text NOT NULL DEFAULT '',
  kind text NOT NULL DEFAULT 'update' CHECK (kind IN ('update','new_service','price','news')),
  published boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Helper: admin check
CREATE OR REPLACE FUNCTION is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin' AND status = 'active');
$$;
REVOKE EXECUTE ON FUNCTION is_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION is_admin() TO authenticated;

CREATE OR REPLACE FUNCTION tier_discount(p_spent numeric)
RETURNS numeric LANGUAGE sql IMMUTABLE SET search_path = public AS $$
  SELECT CASE
    WHEN p_spent >= 5000 THEN 8
    WHEN p_spent >= 2000 THEN 6
    WHEN p_spent >= 1000 THEN 5
    WHEN p_spent >= 500 THEN 4
    WHEN p_spent >= 250 THEN 3
    WHEN p_spent >= 100 THEN 2
    WHEN p_spent >= 50 THEN 1
    ELSE 0 END::numeric;
$$;

-- New account -> profile
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_username text := nullif(trim(NEW.raw_user_meta_data->>'username'), '');
  v_ref uuid;
BEGIN
  IF v_username IS NULL OR v_username !~ '^[A-Za-z0-9_]{3,20}$' THEN
    v_username := regexp_replace(split_part(NEW.email, '@', 1), '[^A-Za-z0-9_]', '', 'g');
    v_username := left(v_username, 14) || substr(md5(random()::text), 1, 5);
  END IF;
  SELECT id INTO v_ref FROM profiles
   WHERE lower(username) = lower(coalesce(NEW.raw_user_meta_data->>'ref', '')) LIMIT 1;
  INSERT INTO profiles (id, username, email, full_name, referred_by)
  VALUES (NEW.id, v_username, NEW.email, coalesce(NEW.raw_user_meta_data->>'full_name', ''), v_ref);
  RETURN NEW;
END;
$$;
REVOKE EXECUTE ON FUNCTION handle_new_user() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION handle_new_user();

-- Ticket message trigger: stamp admin flag + update ticket status
CREATE OR REPLACE FUNCTION ticket_message_stamp()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  NEW.author_id := auth.uid();
  NEW.from_admin := is_admin();
  UPDATE tickets SET status = CASE WHEN NEW.from_admin THEN 'answered' ELSE 'open' END,
                     updated_at = now()
   WHERE id = NEW.ticket_id;
  RETURN NEW;
END;
$$;
REVOKE EXECUTE ON FUNCTION ticket_message_stamp() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS ticket_messages_stamp ON ticket_messages;
CREATE TRIGGER ticket_messages_stamp BEFORE INSERT ON ticket_messages
  FOR EACH ROW EXECUTE FUNCTION ticket_message_stamp();

